// Sahifadagi o'zbekcha matnlarni saqlab qo'yamiz, UZ'ga qaytishda kerak bo'ladi.
const uz = { "meta.title": document.title };
document.querySelectorAll("[data-i18n]").forEach(el => { uz[el.dataset.i18n] = el.textContent; });
document.querySelectorAll("[data-i18n-html]").forEach(el => { uz[el.dataset.i18nHtml] = el.innerHTML; });
translations.uz = uz;

function setLang(lang) {
  const dict = translations[lang] || translations.uz;
  document.documentElement.lang = lang;
  document.title = dict["meta.title"];
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const value = dict[el.dataset.i18n];
    if (value !== undefined) el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const value = dict[el.dataset.i18nHtml];
    if (value !== undefined) el.innerHTML = value;
  });
  document.querySelectorAll(".lang button").forEach(btn => {
    btn.classList.toggle("is-active", btn.dataset.lang === lang);
  });
  try { localStorage.setItem("lang", lang); } catch (e) {}
  document.dispatchEvent(new CustomEvent("langchange"));
}

document.querySelectorAll(".lang button").forEach(btn => {
  btn.addEventListener("click", () => setLang(btn.dataset.lang));
});

let saved = null;
try { saved = localStorage.getItem("lang"); } catch (e) {}
setLang(translations[saved] ? saved : "uz");

document.getElementById("year").textContent = new Date().getFullYear();

