const certSrc = (n, thumb) => `assets/certificates/${thumb ? "thumbs/" : ""}cert-${String(n).padStart(2, "0")}.jpg`;
const currentLang = () => document.documentElement.lang || "uz";

function renderCerts() {
  const lang = currentLang();
  const list = certFilter === "all" ? certs : certs.filter(c => c.c === certFilter);
  const visible = certExpanded || certFilter !== "all" ? list : list.slice(0, CERT_PREVIEW);

  certFilters.replaceChildren(...Object.keys(certCategories).map(key => {
    const count = key === "all" ? certs.length : certs.filter(c => c.c === key).length;
    const chip = document.createElement("button");
    chip.type = "button";
    chip.className = "chip" + (key === certFilter ? " is-active" : "");
    chip.setAttribute("role", "tab");
    chip.setAttribute("aria-selected", key === certFilter);
    chip.innerHTML = `${certCategories[key][lang]} <span class="chip__count">${count}</span>`;
    chip.addEventListener("click", () => { certFilter = key; certExpanded = false; renderCerts(); });
    return chip;
  }));

  certGrid.replaceChildren(...visible.map((item, i) => {
    const card = document.createElement("button");
    card.type = "button";
    card.className = "cert";
    card.style.animationDelay = `${Math.min(i, 8) * 40}ms`;
    card.innerHTML = `
      <span class="cert__img"><img src="${certSrc(item.f, true)}" alt="" loading="lazy"></span>
      <span class="cert__body">
        <span class="cert__tag">${certCategories[item.c][lang]}</span>
        <span class="cert__title"></span>
        <span class="cert__meta"></span>
      </span>`;
    card.querySelector(".cert__title").textContent = item.t[lang];
    card.querySelector(".cert__meta").textContent = item.m[lang];
    card.querySelector("img").alt = item.t[lang];
    card.addEventListener("click", () => {
      openGallery(list.map(c => ({ src: certSrc(c.f), caption: `${c.t[lang]} — ${c.m[lang]}` })), list.indexOf(item));
    });
    return card;
  }));

  certMore.hidden = certFilter !== "all" || certExpanded;
}

certMore.addEventListener("click", () => { certExpanded = true; renderCerts(); });
document.addEventListener("langchange", renderCerts);
renderCerts();

